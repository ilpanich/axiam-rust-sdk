def pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[_\-\s]+", name) if p)


def field_name(name: str) -> tuple[str, str | None]:
    """Rust field name plus the ``serde(rename)`` it needs, if any."""
    ident = name
    if ident in RUST_KEYWORDS:
        return f"r#{ident}", None
    if not re.fullmatch(r"[a-z_][a-z0-9_]*", ident):
        safe = re.sub(r"[^a-z0-9_]", "_", ident.lower())
        return safe, name
    return ident, None


def wrap_doc(text: str, width: int = 74) -> list[str]:
    """Reflow a paragraph to `width`, preserving blank lines.

    rustfmt does not reflow comments, so without this every generated doc
    comment is one 400-column line and the files are unreadable in review.
    """
    import textwrap

    out: list[str] = []
    for para in text.strip().split("\n\n"):
        collapsed = " ".join(para.split())
        if not collapsed:
            out.append("")
            continue
        out.extend(textwrap.wrap(collapsed, width=width) or [""])
        out.append("")
    while out and out[-1] == "":
        out.pop()
    return out


def doc_lines(text: str | None, indent: str = "") -> list[str]:
    """Render an OpenAPI description as Rust doc comments.

    Every generated public item gets one: the crate is `#![warn(missing_docs)]`
    and a generated file that trips it teaches everyone to ignore the lint.
    """
    if not text:
        return []
    out = []
    for raw in wrap_doc(text):
        line = raw.rstrip().replace("\t", "    ")
        # `[` starts an intra-doc link in rustdoc; a stray one from a server
        # doc comment becomes a broken-link warning under `cargo doc`.
        line = line.replace("[", "\\[").replace("]", "\\]")
        out.append(f"{indent}/// {line}".rstrip())
    return out


