def closure(reg: dict[str, Any], types: Types) -> list[str]:
    seeds: set[str] = set()
    for ns in reg["namespaces"].values():
        for op in ns["operations"].values():
            if op["request_schema"]:
                seeds.add(op["request_schema"].lstrip("[]"))
            if op["response"]["schema"]:
                seeds.add(op["response"]["schema"].lstrip("[]"))

    def refs_in(node: Any, out: set[str]) -> None:
        if isinstance(node, dict):
            if "$ref" in node:
                out.add(node["$ref"].rsplit("/", 1)[-1])
            for v in node.values():
                refs_in(v, out)
        elif isinstance(node, list):
            for v in node:
                refs_in(v, out)

    seen: set[str] = set()
    frontier = set(seeds)
    while frontier:
        n = frontier.pop()
        if n in seen or n not in types.schemas:
            continue
        seen.add(n)
        found: set[str] = set()
        refs_in(types.schemas[n], found)
        frontier |= found - seen
    return sorted(seen)


def wire_directions(reg: dict[str, Any]) -> dict[str, set[str]]:
    """schema name -> {"request"} / {"response"} / both.

    A secret-carrying type needs a wire twin, but only in the direction it
    actually travels: a request body needs `From<&Public> for Wire`, a response
    needs `From<Wire> for Public`. Emitting both leaves half of them dead --
    which is fifty uncovered lines in a repo whose coverage floor is 90%, for
    conversions nothing can ever call.
    """
    out: dict[str, set[str]] = {}
    for ns in reg["namespaces"].values():
        for op in ns["operations"].values():
            if op["request_schema"] and op["sensitive_request_fields"]:
                out.setdefault(op["request_schema"].lstrip("[]"), set()).add("request")
            if op["response"]["schema"] and op["sensitive_response_fields"]:
                out.setdefault(op["response"]["schema"].lstrip("[]"), set()).add("response")
    return out


def sensitive_map(reg: dict[str, Any]) -> dict[str, set[str]]:
    """schema name -> the fields §27.5 requires wrapped."""
    out: dict[str, set[str]] = {}
    for ns in reg["namespaces"].values():
        for op in ns["operations"].values():
            if op["request_schema"] and op["sensitive_request_fields"]:
                out.setdefault(op["request_schema"].lstrip("[]"), set()).update(
                    op["sensitive_request_fields"]
                )
            if op["response"]["schema"] and op["sensitive_response_fields"]:
                out.setdefault(op["response"]["schema"].lstrip("[]"), set()).update(
                    op["sensitive_response_fields"]
                )
    return out


def discriminated(schema: dict[str, Any], types: Types) -> list[tuple[str, str, dict]] | None:
    """Detect an internally-tagged union: `oneOf` where each arm pins one tag value.

    Both unions on this surface have that shape (`ProviderConfig` tags on
    `kind`, `MdsRefreshOutcome` on `outcome`), and both are lossy as
    `serde_json::Value` -- which is what a generator that gives up here emits.
    Returns `(tag_field, [(tag_value, payload_schema)])` or `None`.
    """
    variants = schema.get("oneOf")
    if not variants or len(variants) < 2:
        return None
    tag_field: str | None = None
    arms: list[tuple[str, dict[str, Any]]] = []
    for variant in variants:
        parts = variant.get("allOf", [variant])
        tag: tuple[str, str] | None = None
        payload: dict[str, Any] | None = None
        leftovers: dict[str, Any] = {"type": "object", "properties": {}, "required": []}
        for part in parts:
            if "$ref" in part:
                payload = part
                continue
            props = part.get("properties", {})
            for name, prop in props.items():
                values = prop.get("enum")
                if prop.get("type") == "string" and isinstance(values, list) and len(values) == 1:
                    tag = (name, values[0])
                else:
                    leftovers["properties"][name] = prop
                    if name in part.get("required", []):
                        leftovers["required"].append(name)
        if tag is None:
            return None
        if tag_field is None:
            tag_field = tag[0]
        elif tag_field != tag[0]:
            return None
        arms.append((tag[1], payload if payload is not None else leftovers))
    return [(tag_field, value, payload) for value, payload in arms]  # type: ignore[misc]


def emit_models(reg: dict[str, Any], types: Types) -> str:
    names = closure(reg, types)
    secrets = sensitive_map(reg)
    directions = wire_directions(reg)
    out: list[str] = [BANNER, """
//! Request and response types for the CONTRACT §27 management surface.
//!
//! Every type here is derived from a schema in `openapi.json`, reached from
//! the operations `management-registry.json` names. Three shapes recur and are
//! worth knowing before reading:
//!
//! * **Sparse update bodies.** Every field is `Option` and every field is
//!   skipped when `None`, so a body carrying one field changes one field
//!   (§27.4 rule 5). They derive [`Default`], which is what makes
//!   `UpdateUserRequest { email: Some(..), ..Default::default() }` the natural
//!   way to write one. A field that is `None` is *absent from the wire body*,
//!   not sent as `null` -- this SDK cannot express "set this field to null",
//!   which is the safe direction to be inexpressive in.
//! * **Replacement bodies.** `SetOrgSettings`, `EmailConfigOverride`'s org
//!   twin, `WebauthnAttestationPolicy` and `SetMtlsTrustAnchor` have required
//!   fields, because a `PUT` on those routes replaces rather than patches.
//!   The compiler makes you supply all of them, which is the point.
//! * **Types carrying a secret.** These are a public type holding
//!   [`Sensitive<T>`](crate::Sensitive) plus a private wire twin, because §7
//!   forbids `Sensitive` from deriving `Serialize`/`Deserialize` at all -- a
//!   derive on the wrapper would route straight around its redacting `Debug`.

#![allow(clippy::struct_excessive_bools)]

use serde::{Deserialize, Serialize};
use uuid::Uuid;

use crate::Sensitive;
"""]

    for name in names:
        schema = types.schemas[name]
        rname = pascal(name)
        if "enum" in schema:
            out.append(emit_enum(rname, schema))
            continue
        union = discriminated(schema, types)
        if union:
            out.append(emit_union(rname, schema, union, types))
            continue
        out.append(
            emit_struct(rname, name, types, secrets.get(name, set()), directions.get(name, set()))
        )
    return "\n".join(out)


def emit_enum(rname: str, schema: dict[str, Any]) -> str:
    lines = doc_lines(schema.get("description") or f"`{rname}` (generated from openapi.json).")
    lines.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]")
    lines.append("#[non_exhaustive]")
    lines.append(f"pub enum {rname} {{")
    for value in schema["enum"]:
        variant = pascal(str(value))
        lines.extend(doc_lines(f"`{value}`", "    "))
        if variant != value:
            lines.append(f'    #[serde(rename = "{value}")]')
        lines.append(f"    {variant},")
    lines.append("}\n")
    return "\n".join(lines)


def emit_union(rname: str, schema: dict[str, Any], arms: list, types: Types) -> str:
    tag_field = arms[0][0]
    lines = doc_lines(
        schema.get("description")
        or f"`{rname}` -- an internally-tagged union discriminated by `{tag_field}`."
    )
    lines.append("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]")
    lines.append(f'#[serde(tag = "{tag_field}")]')
    lines.append("#[non_exhaustive]")
    lines.append(f"pub enum {rname} {{")
    extra: list[str] = []
    for _, value, payload in arms:
        variant = pascal(str(value))
        lines.extend(doc_lines(f"`{tag_field} = \"{value}\"`", "    "))
        if variant != value:
            lines.append(f'    #[serde(rename = "{value}")]')
        if "$ref" in payload:
            # An `allOf[$ref, {tag}]` arm: the payload is a named struct, and
            # serde flattens a newtype variant under an internal tag.
            lines.append(f"    {variant}({pascal(payload['$ref'].rsplit('/', 1)[-1])}),")
        else:
            # An anonymous arm: synthesize a struct variant inline rather than
            # falling back to `serde_json::Value` and losing the shape.
            lines.append(f"    {variant} {{")
            required = set(payload.get("required", []))
            for pname, pschema in sorted(payload.get("properties", {}).items()):
                ident, rename = field_name(pname)
                ty = types.rust(pschema)
                if pname not in required and not ty.startswith("Option<"):
                    ty = f"Option<{ty}>"
                lines.extend(doc_lines(pschema.get("description") or f"`{pname}`.", "        "))
                if rename:
                    lines.append(f'        #[serde(rename = "{rename}")]')
                if ty.startswith("Option<"):
                    lines.append('        #[serde(default, skip_serializing_if = "Option::is_none")]')
                lines.append(f"        {ident}: {ty},")
            lines.append("    },")
    lines.append("}\n")
    lines.extend(extra)
    return "\n".join(lines)


def emit_struct(
    rname: str, name: str, types: Types, secrets: set[str], directions: set[str]
) -> str:
    props, required, desc = types.flatten(name)
    fields: list[tuple[str, str | None, str, bool, str | None]] = []
    for pname, pschema in sorted(props.items()):
        ident, rename = field_name(pname)
        if pname in secrets:
            # §7: `Sensitive` derives neither `Serialize` nor `Deserialize`, so
            # a struct holding one cannot derive them either. That is why these
            # types get a wire twin below rather than an attribute.
            ty = "Sensitive<String>"
            if pname not in required:
                ty = f"Option<{ty}>"
        else:
            ty = types.rust(pschema)
            if pname not in required and not ty.startswith("Option<"):
                ty = f"Option<{ty}>"
        fields.append((ident, rename, ty, pname in secrets, pschema.get("description")))

    all_optional = all(ty.startswith("Option<") for _, _, ty, _, _ in fields)
    lines = doc_lines(desc or f"`{rname}` (generated from openapi.json).")
    if all_optional and fields:
        lines.extend(doc_lines(
            "\nEvery field is optional, so this is a **sparse** body: what you "
            "leave `None` is left unchanged, and is omitted from the wire "
            "request entirely rather than sent as `null` (§27.4 rule 5). "
            "Construct it with `..Default::default()`."
        ))

    if secrets:
        return emit_sensitive_struct(rname, lines, fields, all_optional, types, directions)

    derives = ["Debug", "Clone", "PartialEq", "Serialize", "Deserialize"]
    if all_optional:
        derives.insert(3, "Default")
    lines.append(f"#[derive({', '.join(derives)})]")
    lines.append(f"pub struct {rname} {{")
    if not fields:
        lines.append("    // The server documents no fields on this schema.")
    for ident, rename, ty, _, fdesc in fields:
        lines.extend(doc_lines(fdesc or f"`{ident}`.", "    "))
        if rename:
            lines.append(f'    #[serde(rename = "{rename}")]')
        if ty.startswith("Option<"):
            lines.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
        lines.append(f"    pub {ident}: {ty},")
    lines.append("}\n")
    return "\n".join(lines)


def emit_sensitive_struct(
    rname: str,
    lines: list[str],
    fields: list[tuple[str, str | None, str, bool, str | None]],
    all_optional: bool,
    types: Types,
    directions: set[str],
) -> str:
    """A public type holding `Sensitive<T>`, plus the wire twin that crosses the socket.

    §7 rule 1 forbids `Sensitive` from deriving either serde trait, so the
    public type cannot derive them either. Splitting the type is the pattern
    the SDK already uses for TOTP enrolment (`src/rest/account.rs`): the wire
    twin is private, holds plain `String`, and the two conversions below are
    the only places a secret is unwrapped or wrapped -- one greppable call each
    (§7 rule 4), rather than fourteen scattered ones.
    """
    lines.extend(doc_lines(
        "\nThis type carries secret material (§27.5), so the field is "
        "[`Sensitive`](crate::Sensitive) and the type derives neither "
        "`Serialize` nor `Deserialize`. Read the secret with `.expose()`, "
        "deliberately, at the point you need it."
    ))
    derives = ["Debug", "Clone"]
    if all_optional:
        derives.append("Default")
    out = list(lines)
    out.append(f"#[derive({', '.join(derives)})]")
    out.append(f"pub struct {rname} {{")
    for ident, _, ty, is_secret, fdesc in fields:
        out.extend(doc_lines(fdesc or f"`{ident}`.", "    "))
        if is_secret:
            # A blank `///` line, or rustdoc runs this into the paragraph above.
            out.append("    ///")
            out.extend(doc_lines(
                "**Secret.** Redacted from every debug and log rendering; "
                "call `.expose()` to read it.", "    "))
        out.append(f"    pub {ident}: {ty},")
    out.append("}\n")

    wire = f"{rname}Wire"
    out.append(f"/// Wire twin of [`{rname}`] -- plain strings, private, never logged.")
    wire_derives = ["Debug", "Clone", "Serialize", "Deserialize"]
    if all_optional:
        wire_derives.insert(2, "Default")
    out.append(f"#[derive({', '.join(wire_derives)})]")
    out.append(f"pub(crate) struct {wire} {{")
    for ident, rename, ty, is_secret, _ in fields:
        wty = ty.replace("Sensitive<String>", "String") if is_secret else ty
        if rename:
            out.append(f'    #[serde(rename = "{rename}")]')
        if wty.startswith("Option<"):
            out.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
        out.append(f"    pub(crate) {ident}: {wty},")
    out.append("}\n")

    if "response" in directions:
        out.append(f"impl From<{wire}> for {rname} {{")
        out.append(f"    fn from(w: {wire}) -> Self {{")
        out.append("        Self {")
        for ident, _, ty, is_secret, _ in fields:
            if not is_secret:
                out.append(f"            {ident}: w.{ident},")
            elif ty.startswith("Option<"):
                out.append(
                    f"            {ident}: w.{ident}.map(crate::management::error::wrap_from_wire),"
                )
            else:
                out.append(
                    f"            {ident}: crate::management::error::wrap_from_wire(w.{ident}),"
                )
        out.append("        }")
        out.append("    }")
        out.append("}\n")

    if "request" in directions:
        out.append(f"impl From<&{rname}> for {wire} {{")
        out.append(f"    fn from(v: &{rname}) -> Self {{")
        out.append("        Self {")
        for ident, _, ty, is_secret, _ in fields:
            if not is_secret:
                # `.clone()` on a `Copy` field is what `clone_on_copy` fires on.
                accessor = f"v.{ident}" if types.is_copy(ty) else f"v.{ident}.clone()"
                out.append(f"            {ident}: {accessor},")
            elif ty.startswith("Option<"):
                out.append(
                    f"            {ident}: v.{ident}.as_ref()"
                    ".map(crate::management::error::expose_for_wire),"
                )
            else:
                out.append(
                    f"            {ident}: crate::management::error::expose_for_wire(&v.{ident}),"
                )
        out.append("        }")
        out.append("    }")
        out.append("}\n")
    return "\n".join(out)


