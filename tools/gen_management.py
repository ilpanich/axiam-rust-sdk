def param_rust_type(fmt: str | None) -> str:
    return "Uuid" if fmt == "uuid" else "&str"


def query_rust_type(qtype: Any) -> str:
    if isinstance(qtype, list):
        qtype = next((t for t in qtype if t != "null"), "string")
    return {"integer": "i64", "boolean": "bool"}.get(qtype, "&str")


def implicit_params(namespace: str, op: dict[str, Any]) -> set[str]:
    names = {p["name"] for p in op["path_params"]}
    out: set[str] = set()
    if "org_id" in names:
        out.add("org_id")
    if "tenant_id" in names and namespace in IMPLICIT_TENANT_NAMESPACES:
        out.add("tenant_id")
    return out


def response_type(op: dict[str, Any], secrets: dict[str, set[str]]) -> tuple[str, str, str]:
    """`(public type, wire type, kind)` for an operation's success body.

    Model types are written `models::X` rather than glob-imported: the schema
    set genuinely contains a `Scope` and an `EmailConfig`, which would collide
    with the scope type and with the `email_config` handle.
    """
    resp = op["response"]
    kind = resp["kind"]
    if kind == "none":
        return "()", "()", "none"
    schema = resp["schema"]
    public = f"models::{pascal(schema)}"
    wire = f"models::{pascal(schema)}Wire" if schema in secrets else public
    if kind == "array":
        return f"Vec<{public}>", f"Vec<{wire}>", "array"
    if kind == "page":
        return f"Page<{public}>", f"Page<{wire}>", "page"
    return public, wire, "object"


def emit_namespace(
    namespace: str, nsdef: dict[str, Any], secrets: dict[str, set[str]], types: Types
) -> tuple[str, list[str]]:
    rname = pascal(namespace)
    ops = nsdef["operations"]
    has_org = any("org_id" in implicit_params(namespace, o) for o in ops.values())
    has_tenant = any("tenant_id" in implicit_params(namespace, o) for o in ops.values())

    lines = [BANNER]
    lines.append(f"//! The `{namespace}` management namespace (CONTRACT §27.1).")
    lines.append("//!")
    for line in wrap_doc(nsdef["doc"]):
        lines.append(f"//! {line}".rstrip())
    lines.append("")
    lines.append("#![allow(clippy::too_many_arguments)]")
    lines.append("")
    # Imports are emitted from what the body actually references. A fixed list
    # is simpler to write and produces `unused_imports` on the namespaces that
    # happen not to paginate -- and CI runs clippy with `-D warnings`.
    import_marker = "@@IMPORTS@@"
    lines.append(import_marker)

    lines.extend(doc_lines(
        f"The `{namespace}` namespace handle.\n\n{nsdef['doc']}\n\n"
        "Acquiring one performs no I/O and allocates nothing meaningful "
        "(§27.2 rule 1); it borrows the client and cannot outlive it."
    ))
    lines.append("#[derive(Clone, Copy)]")
    lines.append(f"pub struct {rname}<'c> {{")
    lines.append("    pub(crate) client: &'c AxiamClient,")
    lines.append("    pub(crate) scope: Scope,")
    lines.append("}")
    lines.append("")
    # A hand-rolled `Debug`: deriving it would require `AxiamClient: Debug`,
    # and a client that rendered itself would render its cookie jar.
    lines.append(f"impl std::fmt::Debug for {rname}<'_> {{")
    lines.append("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {")
    lines.append(f'        f.debug_struct("{rname}").field("scope", &self.scope).finish()')
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append(f"impl<'c> {rname}<'c> {{")
    lines.append("    pub(crate) fn new(client: &'c AxiamClient) -> Self {")
    lines.append("        Self { client, scope: Scope::default() }")
    lines.append("    }")
    lines.append("")
    if has_org:
        lines.extend(doc_lines(
            "Address a different organization than the client's own.\n\n"
            "§27.4 rule 3: the client's `org_id` is the default, and a "
            "platform-admin token legitimately overrides it.", "    "))
        lines.append("    #[must_use]")
        lines.append("    pub fn in_org(mut self, org_id: Uuid) -> Self {")
        lines.append("        self.scope.org_id = Some(org_id);")
        lines.append("        self")
        lines.append("    }")
        lines.append("")
    if has_tenant:
        lines.extend(doc_lines(
            "Address a different tenant than the client's own.\n\n"
            "§27.4 rule 3: the client's `tenant_id` is the default.", "    "))
        lines.append("    #[must_use]")
        lines.append("    pub fn for_tenant(mut self, tenant_id: Uuid) -> Self {")
        lines.append("        self.scope.tenant_id = Some(tenant_id);")
        lines.append("        self")
        lines.append("    }")
        lines.append("")

    test_cases: list[str] = []
    for opname in ops:
        body, case = emit_operation(namespace, opname, ops[opname], secrets, types)
        lines.append(body)
        test_cases.append(case)
    lines.append("}")
    body = "\n".join(lines)

    imports = ["use crate::AxiamError;", "use crate::client::AxiamClient;"]
    if "models::" in body:
        imports.append("use crate::management::models;")
    paging = [n for n in ("Page", "PageRequest", "collect_pages")
              if re.search(rf"\b{n}\b", body.split(import_marker, 1)[1])]
    if paging:
        imports.append(f"use crate::management::page::{{{', '.join(sorted(paging))}}};")
    imports.append("use crate::management::request::{Call, Verb};")
    imports.append("use crate::management::scope::Scope;")
    head = "use uuid::Uuid;\n\n" if re.search(r"\bUuid\b", body.split(import_marker, 1)[1]) else ""
    body = body.replace(import_marker, head + "\n".join(imports) + "\n", 1)
    return body, test_cases


def emit_operation(
    namespace: str,
    opname: str,
    op: dict[str, Any],
    secrets: dict[str, set[str]],
    types: Types,
) -> tuple[str, str]:
    canonical = f"{namespace}.{opname}"
    method = field_name(opname)[0]
    implicit = implicit_params(namespace, op)
    verb = {"GET": "Verb::Get", "POST": "Verb::Post", "PUT": "Verb::Put",
            "DELETE": "Verb::Delete"}[op["method"]]

    args: list[str] = []
    prelude: list[str] = []
    for p in op["path_params"]:
        if p["name"] in implicit:
            resolver = "org" if p["name"] == "org_id" else "tenant"
            prelude.append(
                f'        let {p["name"]} = self.scope.{resolver}(self.client, "{canonical}")?;'
            )
        else:
            args.append(f'{p["name"]}: {param_rust_type(p["format"])}')

    query_extra = [q for q in op["query_params"] if q["name"] not in ("offset", "limit")]
    required_q = [q for q in query_extra if q["required"]]
    optional_q = [q for q in query_extra if not q["required"]]
    filter_ty = None
    if len(optional_q) > 2:
        filter_ty = f"{pascal(namespace)}{pascal(opname)}Filter"
    for q in required_q:
        args.append(f'{field_name(q["name"])[0]}: {query_rust_type(q["type"])}')
    if filter_ty:
        args.append(f"filter: &{filter_ty}")
    else:
        for q in optional_q:
            ident = field_name(q["name"])[0]
            ty = query_rust_type(q["type"])
            args.append(f"{ident}: Option<{ty}>")
    if op["paginated"]:
        args.append("page: PageRequest")

    body_arg = None
    if op["request_body"] == "schema":
        schema = op["request_schema"]
        public = f"models::{pascal(schema)}"
        args.append(f"body: &{public}")
        if schema in secrets:
            prelude.append(f"        let body = models::{pascal(schema)}Wire::from(body);")
            prelude.append("        let body = &body;")
        body_arg = "Some(body)"
    elif op["request_body"] == "untyped":
        args.append("body: &serde_json::Value")
        body_arg = "Some(body)"

    # Query assembly.
    query_lines: list[str] = []
    seeds = [
        f'("{q["name"]}", {field_name(q["name"])[0]}.to_string())' for q in required_q
    ]
    needs_mut = bool(optional_q)
    if op["paginated"]:
        query_lines.append(
            f"        {'let mut query' if (seeds or needs_mut) else 'let query'} = page.query();"
        )
        for seed in seeds:
            query_lines.append(f"        query.push({seed});")
    elif seeds:
        # `Vec::new()` followed immediately by `push` is `vec_init_then_push`.
        query_lines.append(
            f"        {'let mut query' if needs_mut else 'let query'}: "
            f"Vec<(&'static str, String)> = vec![{', '.join(seeds)}];"
        )
    elif needs_mut:
        query_lines.append("        let mut query: Vec<(&'static str, String)> = Vec::new();")
    else:
        query_lines.append("        let query: Vec<(&'static str, String)> = Vec::new();")
    for q in optional_q:
        ident = field_name(q["name"])[0]
        src = f"filter.{ident}.as_deref()" if filter_ty else ident
        if filter_ty:
            query_lines.append(f"        if let Some(v) = {src} {{")
        else:
            query_lines.append(f"        if let Some(v) = {ident} {{")
        query_lines.append(f'            query.push(("{q["name"]}", v.to_string()));')
        query_lines.append("        }")

    public_ty, wire_ty, kind = response_type(op, secrets)
    path_expr = 'format!("{}")'.format(op["path"]) if "{" in op["path"] else f'"{op["path"]}".to_string()'

    # The export's `summary` is the method and path again, which the first
    # doc line already says. Repeating it just pushes the useful text down.
    lines = doc_lines(f"`{op['method']} {op['path']}`", "    ")
    if op["update_style"] == "replace":
        lines.extend(doc_lines(
            "\n**This is a replacement, not a patch** (§27.4 rule 5). Every "
            "field of the body is required, and what you do not carry over "
            "from a prior read is not preserved -- it is overwritten. Read "
            "first, change the field you mean, send the whole thing back.",
            "    "))
    if op["sensitive_response_fields"]:
        lines.extend(doc_lines(
            "\n**Returns secret material, once.** "
            f"`{', '.join(op['sensitive_response_fields'])}` is returned by "
            "this call and by no other; no later `get` will return it again. "
            "Discarding the result destroys the credential (§27.5 rule 3).",
            "    "))
    if op["method"] != "GET":
        lines.extend(doc_lines(
            "\nNot retried on failure (§27.4 rule 8): every write on this "
            "surface is issued exactly once, including the ones that look "
            "idempotent.", "    "))

    signature = f"    pub async fn {method}(&self"
    if args:
        signature += ", " + ", ".join(args)
    signature += f") -> Result<{public_ty}, AxiamError> {{"
    lines.append(signature)
    lines.extend(prelude)
    lines.extend(query_lines)
    lines.append("        let call = Call {")
    lines.append(f'            operation: "{canonical}",')
    lines.append(f"            verb: {verb},")
    lines.append(f'            path_template: "{op["path"]}",')
    lines.append(f"            path: {path_expr},")
    lines.append("            query: &query,")
    lines.append("        };")

    body_expr = body_arg if body_arg else "None::<&()>"
    if kind == "none":
        lines.append(f"        self.client.management_send_no_content(call, {body_expr}).await")
    elif wire_ty != public_ty:
        lines.append(
            f"        let wire: {wire_ty} = self.client.management_send(call, {body_expr}).await?;"
        )
        lines.append(f"        Ok({public_ty}::from(wire))")
    else:
        lines.append(
            f"        self.client.management_send::<_, {public_ty}>(call, {body_expr}).await"
        )
    lines.append("    }")
    lines.append("")

    if op["paginated"]:
        lines.extend(emit_list_all(method, args, canonical, public_ty))

    return "\n".join(lines), canonical


def emit_list_all(method: str, args: list[str], canonical: str, public_ty: str) -> list[str]:
    """The §27.4 rule 4 auto-paging companion for a paginated read."""
    inner = public_ty[len("Page<"):-1]
    lead = [a for a in args if a != "page: PageRequest"]
    forward = [a.split(":")[0] for a in lead]
    sig = f"    pub async fn {method}_all(&self"
    if lead:
        sig += ", " + ", ".join(lead)
    sig += f", start: PageRequest) -> Result<Vec<{inner}>, AxiamError> {{"
    out = doc_lines(
        f"Walk `{canonical}` to exhaustion, concatenating every page.\n\n"
        "The auto-paging form §27.4 rule 4 requires. It stops on an empty "
        "page even if `total` disagrees, so a misreporting server costs one "
        "wasted request rather than an unbounded loop.", "    ")
    out.append(sig)
    call_args = ", ".join(forward + ["p"]) if forward else "p"
    out.append(f"        collect_pages(start, |p| self.{method}({call_args})).await")
    out.append("    }")
    out.append("")
    return out


def emit_filters(namespace: str, nsdef: dict[str, Any]) -> str:
    """Filter structs for operations with more than two optional query parameters.

    Two loose `Option` arguments read fine; six do not -- `audit.list` takes
    six, and a call site passing `None, None, Some(x), None, None, None` is one
    a reader cannot check and a refactor silently reorders.
    """
    out: list[str] = []
    for opname, op in nsdef["operations"].items():
        optional = [
            q for q in op["query_params"] if q["name"] not in ("offset", "limit") and not q["required"]
        ]
        if len(optional) <= 2:
            continue
        rname = f"{pascal(namespace)}{pascal(opname)}Filter"
        out.extend(doc_lines(
            f"Optional filters for `{namespace}.{opname}`.\n\n"
            "Every field is `None` by default; construct with "
            "`..Default::default()` and set only what you mean to filter on."
        ))
        out.append("#[derive(Debug, Clone, Default, PartialEq, Eq)]")
        out.append(f"pub struct {rname} {{")
        for q in optional:
            ident = field_name(q["name"])[0]
            out.extend(doc_lines(f"Filter on `{q['name']}`.", "    "))
            out.append(f"    pub {ident}: Option<String>,")
        out.append("}")
        out.append("")
    return "\n".join(out)


def emit_ops_mod(reg: dict[str, Any]) -> str:
    lines = [BANNER]
    lines.append("//! One handle per §27 namespace, and the accessors that reach them.")
    lines.append("//!")
    lines.append("//! §27.2 makes this namespacing normative rather than stylistic: twenty")
    lines.append("//! namespaces have a `list` and fourteen a `get`, so flattening 146")
    lines.append("//! operations onto the client would need a disambiguating prefix invented")
    lines.append("//! once per operation -- and would bury the eight §1 methods most callers")
    lines.append("//! actually want under five times as many they do not.")
    lines.append("")
    for ns in reg["namespaces"]:
        lines.append(f"pub mod {ns};")
    lines.append("")
    lines.append("use crate::client::AxiamClient;")
    lines.append("")
    lines.append("impl AxiamClient {")
    for ns, nsdef in reg["namespaces"].items():
        rname = pascal(ns)
        lines.extend(doc_lines(
            f"The `{ns}` management namespace.\n\n{nsdef['doc']}\n\n"
            f"Acquiring the handle performs no I/O (§27.2 rule 1).", "    "))
        lines.append("    #[must_use]")
        lines.append(f"    pub fn {ns}(&self) -> {ns}::{rname}<'_> {{")
        lines.append(f"        {ns}::{rname}::new(self)")
        lines.append("    }")
        lines.append("")
    lines.append("}")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Example instances
# ---------------------------------------------------------------------------
# The generated test needs two things per operation: a JSON body the server can
# plausibly answer with, and a Rust value to send. Both come from the same
# schemas the models do, which is what makes the test worth running -- it
# deserializes the server's *declared* shape into the generated type, so a
# wrong `$ref`, a missed required field, a bad enum rename or a page envelope
# classified as an object fails there rather than at a user.

EXAMPLE_UUID = "11111111-1111-4111-8111-111111111111"
EXAMPLE_TIME = "2026-08-26T00:00:00Z"


def example_json(schema: dict[str, Any], types: Types, depth: int = 0) -> Any:
    """A minimal instance satisfying `schema`: required fields only."""
    if depth > 6:
        return None
    if "$ref" in schema:
        return example_json(types.resolve(schema), types, depth + 1)
    inner = types.nullable_ref(schema)
    if inner:
        return example_json(types.schemas[inner], types, depth + 1)
    if "enum" in schema:
        return schema["enum"][0]
    variants = schema.get("oneOf") or schema.get("anyOf")
    if variants:
        for v in variants:
            if v.get("type") != "null":
                return example_json(v, types, depth + 1)
        return None
    if "allOf" in schema:
        merged: dict[str, Any] = {}
        for part in schema["allOf"]:
            got = example_json(part, types, depth + 1)
            if isinstance(got, dict):
                merged.update(got)
        return merged

    t = schema.get("type")
    if isinstance(t, list):
        t = next((x for x in t if x != "null"), None)
    if t == "object" or (t is None and schema.get("properties")):
        out: dict[str, Any] = {}
        required = set(schema.get("required", []))
        for name, prop in schema.get("properties", {}).items():
            if name in required:
                out[name] = example_json(prop, types, depth + 1)
        return out
    if t == "array":
        return []
    if t == "integer":
        return 1
    if t == "number":
        return 1.0
    if t == "boolean":
        return True
    if t == "string":
        fmt = schema.get("format")
        if fmt == "uuid":
            return EXAMPLE_UUID
        if fmt == "date-time":
            return EXAMPLE_TIME
        return "example"
    return {}


def example_response(op: dict[str, Any], types: Types) -> str:
    """The JSON the mock server answers with, as a Rust raw string literal."""
    resp = op["response"]
    if resp["kind"] == "none":
        return '""'
    one = example_json(types.schemas[resp["schema"]], types)
    if resp["kind"] == "array":
        body: Any = [one]
    elif resp["kind"] == "page":
        # `total` deliberately exceeds `items.len()` nowhere here -- the
        # auto-paging walk is asserted properly in the hand-written tests, and
        # a generated fixture claiming more would loop.
        body = {"items": [one], "total": 1, "offset": 0, "limit": 50}
    else:
        body = one
    return 'r#"' + json.dumps(body) + '"#'


def rust_literal(schema: dict[str, Any], types: Types, secrets: set[str],
                 field: str | None = None, depth: int = 0) -> str:
    """A Rust expression constructing a minimal valid value for `schema`."""
    if depth > 6:
        return "Default::default()"
    if field and field in secrets:
        return 'Sensitive::new("example".to_string())'
    if "$ref" in schema:
        return struct_literal(schema["$ref"].rsplit("/", 1)[-1], types, secrets, depth + 1)
    if types.nullable_ref(schema):
        return "None"
    if schema.get("oneOf") or schema.get("anyOf"):
        return "None"

    t = schema.get("type")
    if isinstance(t, list) and "null" in t:
        return "None"
    if t == "array":
        return "Vec::new()"
    if t == "integer":
        return "1"
    if t == "number":
        return "1.0"
    if t == "boolean":
        return "true"
    if t == "string":
        fmt = schema.get("format")
        if fmt == "uuid":
            return "example_id()"
        if fmt == "date-time":
            return f'"{EXAMPLE_TIME}".to_string()'
        return '"example".to_string()'
    if t == "object" or not schema:
        return "serde_json::json!({})"
    return "Default::default()"


def struct_literal(name: str, types: Types, secrets: set[str], depth: int = 0) -> str:
    """Construct a named model, required fields only, the rest defaulted."""
    schema = types.schemas.get(name, {})
    if "enum" in schema:
        return f"models::{pascal(name)}::{pascal(str(schema['enum'][0]))}"
    if schema.get("oneOf"):
        union = discriminated(schema, types)
        if union:
            _, value, payload = union[0]
            if "$ref" in payload:
                inner = struct_literal(
                    payload["$ref"].rsplit("/", 1)[-1], types, secrets, depth + 1
                )
                return f"models::{pascal(name)}::{pascal(str(value))}({inner})"
        return "Default::default()"

    props, required, _ = types.flatten(name)
    own = secrets if depth == 0 else set()
    if not required and props:
        # All-optional bodies derive `Default`, which is both shorter and the
        # shape §27.4 rule 5 wants callers reaching for.
        return f"models::{pascal(name)}::default()"
    # Every field, not only the required ones: the Rust struct has a field per
    # property, and an initializer that names a subset does not compile. The
    # optional ones are `None`, which is also what a caller would write.
    parts = []
    for pname in sorted(props):
        value = (
            rust_literal(props[pname], types, own, pname, depth + 1)
            if pname in required
            else "None"
        )
        parts.append(f"{field_name(pname)[0]}: {value}")
    return f"models::{pascal(name)} {{ {', '.join(parts)} }}"


def call_arguments(
    namespace: str, opname: str, op: dict[str, Any], types: Types, secrets: dict[str, set[str]]
) -> tuple[list[str], str]:
    """`(call arguments, mock path)` for one operation in the generated test."""
    implicit = implicit_params(namespace, op)
    args: list[str] = []
    route = op["path"]
    for prm in op["path_params"]:
        name = prm["name"]
        if name in implicit:
            value = "{ORG_ID}" if name == "org_id" else "{TENANT_ID}"
            route = route.replace("{" + name + "}", value)
            continue
        if prm["format"] == "uuid":
            args.append("example_id()")
            route = route.replace("{" + name + "}", "{EXAMPLE_ID}")
        else:
            args.append('"example"')
            route = route.replace("{" + name + "}", "example")

    extra = [q for q in op["query_params"] if q["name"] not in ("offset", "limit")]
    required_q = [q for q in extra if q["required"]]
    optional_q = [q for q in extra if not q["required"]]
    for _ in required_q:
        args.append('"example"')
    if len(optional_q) > 2:
        filter_ty = f"{pascal(namespace)}{pascal(opname)}Filter"
        args.append(f"&{namespace}::{filter_ty}::default()")
    else:
        args.extend("None" for _ in optional_q)
    if op["paginated"]:
        args.append("PageRequest::first(50)")

    if op["request_body"] == "schema":
        args.append(f"&{struct_literal(op['request_schema'], types, secrets.get(op['request_schema'], set()))}")
    elif op["request_body"] == "untyped":
        args.append("&serde_json::json!({})")
    return args, route


def emit_test(reg: dict[str, Any], types: Types, secrets: dict[str, set[str]]) -> str:
    """One test per namespace, reaching every operation in it.

    This exists because of the coverage floor, and because a generated surface
    with no generated test is a surface whose first caller is its first test.
    Each case mounts the response the OpenAPI schema *declares* and asserts the
    SDK deserializes it into the generated type -- so a wrong `$ref`, a missed
    required field, a bad enum rename or a page envelope classified as an
    object fails here rather than at a user.
    """
    lines = [BANNER]
    lines.append("//! Generated §27 surface conformance: every operation is reached once.")
    lines.append("//!")
    lines.append("//! Per operation: the SDK issues the registry's method against the registry's")
    lines.append("//! path, and deserializes the response shape `openapi.json` declares. Semantics")
    lines.append("//! that are not per-operation -- sparse-update key sets, secret redaction,")
    lines.append("//! error mapping, pagination walks, the manifest -- are tested by hand in the")
    lines.append("//! other `tests/management_*.rs` files.")
    lines.append("")
    lines.append('#![cfg(feature = "rest")]')
    lines.append("")
    lines.append("mod management_support;")
    lines.append("")
    lines.append("use axiam_sdk::Sensitive;")
    lines.append("use axiam_sdk::management::PageRequest;")
    lines.append("use axiam_sdk::management::models;")
    lines.append("use axiam_sdk::management::ops::*;")
    lines.append("use uuid::Uuid;")
    lines.append("use wiremock::MockServer;")
    lines.append("")
    lines.append("use management_support::{")
    lines.append("    EXAMPLE_ID, ORG_ID, TENANT_ID, expected_surface, logged_in_client, mount,")
    lines.append("};")
    lines.append("")
    lines.append("fn example_id() -> Uuid {")
    lines.append("    Uuid::parse_str(EXAMPLE_ID).expect(\"fixture id parses\")")
    lines.append("}")
    lines.append("")

    all_ops = [f"{ns}.{op}" for ns, nsd in reg["namespaces"].items() for op in nsd["operations"]]
    lines.append("/// Every operation this file exercises, in registry order.")
    lines.append("///")
    lines.append("/// §27.9: assert the count and the names, so a partial regeneration fails")
    lines.append("/// here instead of quietly shipping 140 of 146.")
    lines.append(f"const EXERCISED: [&str; {len(all_ops)}] = [")
    for name in all_ops:
        lines.append(f'    "{name}",')
    lines.append("];")
    lines.append("")
    lines.append("#[test]")
    lines.append("fn generated_surface_matches_the_registry() {")
    lines.append("    let mut expected = expected_surface();")
    lines.append("    let mut exercised: Vec<String> =")
    lines.append("        EXERCISED.iter().map(|s| (*s).to_string()).collect();")
    lines.append("    expected.sort();")
    lines.append("    exercised.sort();")
    lines.append("    assert_eq!(")
    lines.append("        exercised, expected,")
    lines.append('        "the generated surface and management-registry.json disagree"')
    lines.append("    );")
    lines.append("}")
    lines.append("")

    for namespace, nsdef in reg["namespaces"].items():
        lines.append(f"/// Reaches every operation in the `{namespace}` namespace.")
        lines.append("#[tokio::test]")
        lines.append(f"async fn {namespace}_surface() {{")
        lines.append("    let server = MockServer::start().await;")
        lines.append("    let client = logged_in_client(&server).await;")
        lines.append("")
        for opname, op in nsdef["operations"].items():
            canonical = f"{namespace}.{opname}"
            args, route = call_arguments(namespace, opname, op, types, secrets)
            body = example_response(op, types)
            status = op["response"]["status"]
            method_name = field_name(opname)[0]
            lines.append(f"    // {canonical}")
            # `format!` with nothing to substitute is `clippy::useless_format`.
            route_expr = f'&format!("{route}")' if "{" in route else f'"{route}"'
            lines.append(
                f'    mount(&server, "{op["method"]}", {route_expr}, {status}, {body}).await;'
            )
            call = f"client.{namespace}().{method_name}({', '.join(args)})"
            lines.append(f'    {call}')
            lines.append(f'        .await')
            lines.append(f'        .expect("{canonical}");')
            if op["paginated"]:
                lines.append(
                    f'    client.{namespace}().{method_name}_all('
                    + ", ".join(a for a in args if a != "PageRequest::first(50)")
                    + (", " if len(args) > 1 else "")
                    + "PageRequest::first(50))"
                )
                lines.append("        .await")
                lines.append(f'        .expect("{canonical} auto-paging");')
            lines.append("")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed output is not what this run produces")
    args = ap.parse_args()

    reg = json.loads(REGISTRY.read_text())
    spec = json.loads(OPENAPI.read_text())
    types = Types(spec)
    secrets = sensitive_map(reg)

    written: dict[Path, str] = {MODELS_OUT: emit_models(reg, types)}
    for ns, nsdef in reg["namespaces"].items():
        body, _ = emit_namespace(ns, nsdef, secrets, types)
        filters = emit_filters(ns, nsdef)
        if filters:
            body = body.replace("impl<'c>", filters + "\nimpl<'c>", 1)
        written[OPS_DIR / f"{ns}.rs"] = body
    written[OPS_DIR / "mod.rs"] = emit_ops_mod(reg)
    written[TEST_OUT] = emit_test(reg, types, secrets)

    if args.check:
        stale = [p for p, body in written.items() if not p.exists() or p.read_text() != body]
        if stale:
            for p in stale:
                print(f"FAIL: {p.relative_to(ROOT)} is stale", file=sys.stderr)
            print("run tools/gen_management.py", file=sys.stderr)
            return 1
        print(f"OK: {len(written)} generated files are current "
              f"({reg['operation_count']} operations)")
        return 0

    OPS_DIR.mkdir(parents=True, exist_ok=True)
    for path, body in written.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body if body.endswith("\n") else body + "\n")
    print(f"wrote {len(written)} files: {reg['operation_count']} operations across "
          f"{reg['namespace_count']} namespaces")
    # rustfmt is the formatting authority; generating pre-formatted text by
    # hand is a losing game and CI runs `cargo fmt --check`.
    subprocess.run(["cargo", "fmt"], cwd=ROOT, check=False)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
