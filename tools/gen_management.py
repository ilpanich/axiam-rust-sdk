#: Rust types the generator emits or uses that implement `Copy`. Cloning one
#: is what `clippy::clone_on_copy` fires on, and the generated wire conversions
#: would otherwise do it fifteen times for `Uuid` alone.
COPY_PRIMITIVES = {"Uuid", "bool", "i32", "i64", "f64", "u32", "u64"}


class Types:
    def __init__(self, spec: dict[str, Any]) -> None:
        self.spec = spec
        self.schemas = spec["components"]["schemas"]
        #: Structs synthesized for anonymous `oneOf` variants, name -> schema.
        self.synthetic: dict[str, dict[str, Any]] = {}
        #: Every string-enum schema; all of them are emitted `Copy`.
        self.copy_enums = {
            pascal(n) for n, sc in self.schemas.items() if "enum" in sc
        }

    def is_copy(self, ty: str) -> bool:
        """Whether a generated Rust type is `Copy`, `Option` unwrapped."""
        if ty.startswith("Option<") and ty.endswith(">"):
            return self.is_copy(ty[len("Option<"):-1])
        return ty in COPY_PRIMITIVES or ty in self.copy_enums

    def resolve(self, schema: dict[str, Any]) -> dict[str, Any]:
        while "$ref" in schema:
            schema = self.schemas[schema["$ref"].rsplit("/", 1)[-1]]
        return schema

    @staticmethod
    def nullable_ref(schema: dict[str, Any]) -> str | None:
        """`{oneOf: [{type: null}, {$ref: X}]}` -- utoipa's `Option<X>`."""
        variants = schema.get("oneOf")
        if not variants or len(variants) != 2:
            return None
        nulls = [v for v in variants if v.get("type") == "null"]
        refs = [v for v in variants if "$ref" in v]
        if len(nulls) == 1 and len(refs) == 1:
            return refs[0]["$ref"].rsplit("/", 1)[-1]
        return None

    def rust(self, schema: dict[str, Any]) -> str:
        """The Rust type for a property schema, `Option<..>` included."""
        if "$ref" in schema:
            return pascal(schema["$ref"].rsplit("/", 1)[-1])
        inner = self.nullable_ref(schema)
        if inner:
            return f"Option<{pascal(inner)}>"
        if "oneOf" in schema or "anyOf" in schema:
            return "serde_json::Value"
        if not schema:
            return "serde_json::Value"

        t = schema.get("type")
        optional = False
        if isinstance(t, list):
            optional = "null" in t
            rest = [x for x in t if x != "null"]
            t = rest[0] if rest else None
            schema = {k: v for k, v in schema.items() if k != "type"}
            schema["type"] = t

        base: str
        if t == "string":
            fmt = schema.get("format")
            if fmt == "uuid":
                base = "Uuid"
            else:
                # `date-time` maps to String on purpose: `chrono` is an
                # optional dependency of this crate, and making 60 timestamp
                # fields require it would turn a feature flag into a hard one.
                base = "String"
        elif t == "integer":
            base = {"int32": "i32", "int64": "i64"}.get(schema.get("format", ""), "i64")
        elif t == "number":
            base = "f64"
        elif t == "boolean":
            base = "bool"
        elif t == "array":
            base = f"Vec<{self.rust(schema.get('items', {}))}>"
        elif t == "object":
            base = "serde_json::Value"
        else:
            base = "serde_json::Value"
        return f"Option<{base}>" if optional else base

    def flatten(self, name: str) -> tuple[dict[str, Any], set[str], str | None]:
        """Properties + required set of a schema, `allOf` composition resolved."""
        schema = self.schemas[name]
        props: dict[str, Any] = {}
        required: set[str] = set()
        desc = schema.get("description")

        def absorb(node: dict[str, Any]) -> None:
            node = self.resolve(node) if "$ref" in node else node
            props.update(node.get("properties", {}))
            required.update(node.get("required", []))
            for sub in node.get("allOf", []):
                absorb(sub)

        absorb(schema)
        return props, required, desc


