#!/usr/bin/env python3
"""Generate the CONTRACT §27 management surface for the Rust SDK.

Reads the two vendored artifacts -- ``management-registry.json`` (the
normative §27 vocabulary) and ``openapi.json`` (the schemas it refers to) --
and writes:

    src/management/models.rs                  the request/response types
    src/management/ops/<namespace>.rs         one handle per namespace
    src/management/ops/mod.rs
    tests/management_surface_generated.rs     one wire assertion per operation

§27.8 draws the line this script works to: the models and the raw calls are
generated, everything ergonomic is not. Nothing here opens a connection or
maps an error -- every generated call funnels into
``AxiamClient::management_send``, so §3, §4, §5, §6, §9, §16 and §19 are
inherited rather than reimplemented 146 times.

The generated test matters as much as the generated code. The SDK's coverage
floor is 90% of lines, and 146 hand-written smoke tests is the kind of chore
that gets half-done; generating them from the same registry means a new
operation arrives with its own coverage or not at all.

Usage:
    tools/gen_management.py            # write
    tools/gen_management.py --check    # verify committed output is current
"""

